from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from .features import build_features
from .sections import SECTIONS, Section

log = logging.getLogger("vidscreen")
DEFAULT_SECTIONS = ["quality", "features", "overview", "duration", "views", "engagement", "upload_trends", "language_country",
                    "creators", "subtopics", "query_analysis", "text_analysis", "transcripts", "techniques", "outcome"]
DATASETS = {
    "strict": "the strict relevant set (videos the screening kept as relevant: human-labeled relevant plus model-selected strict-zone videos)",
    "all": "all cleaned videos with their screening outcome (relevant, audit and irrelevant groups together)",
}
GROUP_FILES = ("relevant_strict_videos.csv", "audit_videos.csv", "irrelevant_videos.csv")


def load_dataset(settings, ds: str) -> pd.DataFrame | None:
    """strict -> relevant_strict_videos.csv; all -> the three screening group files stacked (same rows as screening_results.csv, with transcripts)."""
    sdir = settings.final_dir / "screening"
    names = GROUP_FILES[:1] if ds == "strict" else GROUP_FILES
    missing = [n for n in names if not (sdir / n).exists()]
    if missing:
        log.warning("Skipping %s: missing %s in %s", ds, ", ".join(missing), sdir)
        return None
    parts = [pd.read_csv(sdir / n, dtype={"video_id": str}, encoding="utf-8-sig") for n in names]
    d = pd.concat(parts, ignore_index=True)
    return d.drop_duplicates("video_uid")


def write_report(ds: str, d: pd.DataFrame, sections: list, out: Path) -> Path:
    L = [f"# Exploratory data analysis: {ds} dataset", "",
         f"Dataset: {DATASETS[ds]}. {len(d):,} videos ({', '.join(f'{p} {(d.platform == p).sum():,}' for p in ('youtube', 'tiktok'))}). Collection date used as the reference date: {d['reference_date'].iloc[0]}.",
         "All numbers in this report are generated by `scripts/run_eda.py` from the data; nothing is typed by hand.",
         "Statistical tests treat videos as independent, although some creators contribute many videos, so p-values are optimistic; effect sizes and confidence intervals are therefore reported, and `scripts/run_eda_robustness.py` repeats the key results with a cap on videos per creator.", ""]
    for sec in sections:
        L += [f"## {sec.title}", "", sec.intro, ""]
        L += [f"- {f}" for f in sec.findings] + [""]
        for fig in sec.figures:
            L += [f"![{fig}](figures/{fig})", ""]
        if sec.tables:
            L += ["Tables: " + ", ".join(f"`tables/{t}`" for t in sec.tables), ""]
        L += [f"*Note: {n}*" for n in sec.notes] + [""]
    path = out / "EDA_report.md"
    path.write_text("\n".join(L), encoding="utf-8")
    return path


def run_eda(settings, datasets=("strict", "all"), sections=None, out_root: Path = None) -> dict:
    sections = sections or DEFAULT_SECTIONS
    out_root = Path(out_root) if out_root else settings.root / "reports" / "eda"
    done = {}
    for ds in datasets:
        raw = load_dataset(settings, ds)
        if raw is None:
            continue
        log.info("[%s] building features for %d videos ...", ds, len(raw))
        d = build_features(raw)
        feat_dir = settings.final_dir / "eda"
        feat_dir.mkdir(parents=True, exist_ok=True)
        d.to_csv(feat_dir / f"features_{ds}.csv", index=False, encoding="utf-8-sig")
        out = out_root / ds
        out.mkdir(parents=True, exist_ok=True)
        secs = []
        for name in sections:
            if name not in SECTIONS:
                raise SystemExit(f"Unknown section '{name}'. Available: {', '.join(SECTIONS)}")
            log.info("[%s] section: %s", ds, name)
            secs.append(SECTIONS[name](d, out))
        done[ds] = write_report(ds, d, secs, out)
        log.info("[%s] report: %s", ds, done[ds])
    return done
